def payloads_of_sse(raw: str) -> list:
    """The `data:` payloads of an SSE body, in order, `[DONE]` excluded."""
    out = []
    for line in raw.splitlines():
        line = line.strip()
        if not line.startswith("data:"):
            continue
        data = line[len("data:") :].strip()
        if data == "" or data == "[DONE]":
            continue
        out.append(data)
    return out


def write_fixture(out: str, raw: str, payloads: list, sse_path: str = "") -> str:
    """Write the raw bytes and the payload lines. Returns the `.sse` path."""
    sse = sse_path or (out + ".sse")
    with open(sse, "w", encoding="utf-8") as fh:
        fh.write(raw)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(payloads) + "\n")
    return sse


def write_expectations(out: str, scenario: str, meta: dict) -> None:
    """The calls the adapter must produce from `<out>.sse`, as a golden file."""
    path = out.replace(".jsonl", "") + ".expect.json"
    body = {
        "transport": "loopback-sse",
        "scenario": scenario,
        "wire": "anthropic/v1/messages",
        "provider": "anthropic",
        "calls": meta["calls"],
    }
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(body, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.write("\n")


def run_adapter(cli: str, sse_path: str, provider: str):
    """Run the real `code/llm` adapter over the recorded bytes."""
    with open(sse_path, "rb") as fh:
        return subprocess.run(
            [cli, "llm", "--provider", provider, "--sse"],
            stdin=fh,
            capture_output=True,
            text=True,
            timeout=120,
        )


def fixture_paths(out: str) -> tuple:
    """(jsonl, sse, adapter, provenance) for a fixture path or its base."""
    base = out[: -len(".jsonl")] if out.endswith(".jsonl") else out
    return base + ".jsonl", base + ".sse", base + ".adapter.jsonl", \
        base + ".provenance.json"


def payload_type(payload: str) -> str:
    try:
        v = json.loads(payload)
    except ValueError:
        return ""
    return v.get("type", "") if isinstance(v, dict) else ""


def cut_live_stream(raw: str, keep_events: int, cut_before_last: str) -> str:
    """Keep a real prefix of `raw`: drop whole SSE events from the tail.

    A dropped connection ends *between* events, so the prefix is cut on an event
    boundary and the kept bytes are still exactly the bytes that arrived.
    `cut_before_last` drops from the *last* event of that type, which is how a
    `content_block_stop` for the final tool block is removed together with the
    `message_delta`/`message_stop` that follow it.
    """
    blocks = [b for b in raw.split("\n\n") if b != ""]
    data_of = []
    for block in blocks:
        data = ""
        for line in block.split("\n"):
            if line.startswith("data:"):
                data = line[len("data:"):].strip()
                break
        data_of.append(payload_type(data) if data else "")
    limit = len(blocks)
    if keep_events:
        seen, at = 0, len(blocks)
        for i, t in enumerate(data_of):
            if t:
                seen += 1
                if seen > keep_events:
                    at = i
                    break
        limit = min(limit, at)
    if cut_before_last:
        last = -1
        for i, t in enumerate(data_of):
            if t == cut_before_last:
                last = i
        if last >= 0:
            limit = min(limit, last)
    return "\n\n".join(blocks[:limit]) + "\n\n"


def live_provenance(url: str, provider: str, scene: str, raw: str,
                    original_events: int) -> dict:
    """A `.provenance.json` next to a live capture: where the bytes came from.

    It contains no credential, only facts a reviewer can check, so a capture can
    be committed without leaking anything.
    """
    return {
        "transport": "live-http-sse",
        "vendor_capture": True,
        "provider": provider,
        "endpoint": url,
        "endpoint_label": "",
        "scene": scene,
        "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "sse_events_kept": len(payloads_of_sse(raw)),
        "sse_events_received": original_events,
        "truncated_by_recorder": len(payloads_of_sse(raw)) < original_events,
        "response_bytes": len(raw.encode("utf-8")),
        "response_sha256": hashlib.sha256(raw.encode("utf-8")).hexdigest(),
    }


def derive_cut_main(args) -> int:
    """Write a fixture from an already recorded capture, cut on an event edge."""
    out, sse_path, adapter_path, prov_path = fixture_paths(args.out)
    with open(args.derive_cut, "r", encoding="utf-8") as fh:
        original = fh.read()
    received = len(payloads_of_sse(original))
    raw = cut_live_stream(original, args.keep_events, args.cut_before_last)
    payloads = payloads_of_sse(raw)
    if not payloads:
        print("the cut left no payload; nothing was written.", file=sys.stderr)
        return 1
    for p in payloads:
        try:
            json.loads(p)
        except ValueError:
            print("payload is not JSON: %s" % p[:120], file=sys.stderr)
            return 1
    write_fixture(out, raw, payloads, sse_path)
    try:
        with open(os.path.join(os.path.dirname(args.derive_cut),
                               os.path.basename(args.derive_cut)
                               .replace(".sse", ".provenance.json")),
                  "r", encoding="utf-8") as fh:
            body = json.load(fh)
    except (OSError, ValueError):
        body = live_provenance("(derived)", "anthropic", "", raw, received)
    body["derived_from"] = args.derive_cut
    body["keep_events"] = args.keep_events
    body["cut_before_last"] = args.cut_before_last
    body["derived_from_sha256"] = hashlib.sha256(
        original.encode("utf-8")).hexdigest()
    body["sse_events_kept"] = len(payloads)
    body["sse_events_received"] = received
    body["truncated_by_recorder"] = True
    body["response_bytes"] = len(raw.encode("utf-8"))
    body["response_sha256"] = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    with open(prov_path, "w", encoding="utf-8") as fh:
        json.dump(body, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.write("\n")
    print("wrote %d/%d event payloads to %s (derived from %s)"
          % (len(payloads), received, out, args.derive_cut))
    print("provenance: %s" % prov_path)
    if args.cli:
        proc = run_adapter(args.cli, sse_path, args.provider or "anthropic")
        with open(adapter_path, "w", encoding="utf-8") as fh:
            fh.write(proc.stdout)
        print("adapter (rc=%d) wrote %s" % (proc.returncode, adapter_path))
        for line in proc.stdout.splitlines():
            print("  " + line)
        if proc.returncode != 0:
            print(proc.stderr[:400], file=sys.stderr)
            return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", choices=["anthropic", "openai"])
    ap.add_argument("--out", required=True,
                    help="fixture path; in --loopback mode, the output directory")
    ap.add_argument("--text", action="store_true")
    ap.add_argument("--model", default="",
                    help="model id to request (default: the settings file's "
                         "ANTHROPIC_MODEL, else claude-sonnet-4-5)")
    ap.add_argument("--scene", default="tool_call", choices=list(LIVE_SCENES),
                    help="which live request to make (live mode only)")
    ap.add_argument("--endpoint-label", default="",
                    help="short name of the endpoint, for the provenance file")
    ap.add_argument("--derive-cut", default="", metavar="SSE",
                    help="cut an already recorded .sse at an event boundary and "
                         "write the fixture, without calling the provider again")
    ap.add_argument("--keep-events", type=int, default=0,
                    help="keep only the first N data: payloads (live mode only)")
    ap.add_argument("--cut-before-last", default="",
                    metavar="TYPE",
                    help="keep only the events before the last payload of this "
                         "`type`, so the fixture ends the way a dropped "
                         "connection ends (live mode only, or --derive-cut)")
    ap.add_argument("--loopback", action="store_true",
                    help="serve a real SSE stream on 127.0.0.1 and read it back")
    ap.add_argument("--scenario", default="all",
                    choices=["all", *SCENARIOS.keys()])
    ap.add_argument("--stamp", action="store_true",
                    help="put a timestamp in the provenance line (breaks "
                         "byte-for-byte regeneration)")
    ap.add_argument("--cli", default="",
                    help="also run this jsonmend binary over the recorded bytes "
                         "and save `<out>.adapter.jsonl`")
    ap.add_argument("--base-url", default="",
                    help="override the endpoint (Anthropic-compatible)")
    ap.add_argument("--auth-header", default=None,
                    choices=["x-api-key", "authorization"],
                    help="default: x-api-key, or authorization with "
                         "--from-claude-settings")
    ap.add_argument("--from-claude-settings", nargs="?", const="",
                    default=None,
                    help="take ANTHROPIC_AUTH_TOKEN/ANTHROPIC_BASE_URL from a "
                         "Claude Code settings file (default "
                         "~/.claude/settings.json)")
    args = ap.parse_args()

    if args.loopback:
        return loopback_main(args)

    if args.derive_cut:
        return derive_cut_main(args)

    if args.provider is None:
        print("--provider is required unless --loopback is given.",
              file=sys.stderr)
        return 2

    args.out, sse_path, adapter_path, prov_path = fixture_paths(args.out)
    base_url = args.base_url
    auth_header = args.auth_header
    model = args.model
    key = ""
    if args.provider == "anthropic":
        if args.from_claude_settings is not None:
            path = args.from_claude_settings or os.path.expanduser(
                "~/.claude/settings.json")
            env = claude_settings_env(path)
            key = os.environ.get("ANTHROPIC_AUTH_TOKEN") or env.get(
                "ANTHROPIC_AUTH_TOKEN", "")
            base_url = base_url or env.get("ANTHROPIC_BASE_URL", "")
            if not model:
                # e.g. `LongCat-2.0[1M]`: the bracket is a context-window
                # variant marker, not part of the model id the API accepts.
                model = (env.get("ANTHROPIC_MODEL")
                         or env.get("ANTHROPIC_DEFAULT_HAIKU_MODEL", ""))
                model = model.split("[")[0]
            if not key:
                print("%s carried no ANTHROPIC_AUTH_TOKEN." % path,
                      file=sys.stderr)
                return 2
        else:
            key = os.environ.get("ANTHROPIC_API_KEY", "")
    else:
        key = os.environ.get("OPENAI_API_KEY", "")
    if auth_header is None:
        auth_header = "authorization" if args.from_claude_settings is not None \
            else "x-api-key"
    if key == "":
        print("no %s credential available; nothing was recorded."
              % ("Anthropic" if args.provider == "anthropic" else "OpenAI"),
              file=sys.stderr)
        return 2

    if args.provider == "anthropic":
        if base_url:
            url = base_url.rstrip("/") + "/v1/messages"
        else:
            url = ANTHROPIC_URL
        raw = record_anthropic(url, key, args.text, auth_header, args.scene,
                               model)
    else:
        raw = record_openai(key, args.text)

    received = len(payloads_of_sse(raw))
    if args.keep_events or args.cut_before_last:
        raw = cut_live_stream(raw, args.keep_events, args.cut_before_last)
    payloads = payloads_of_sse(raw)
    if not payloads:
        print("the stream carried no data: payload; nothing was written.",
              file=sys.stderr)
        return 1
    for p in payloads:
        try:
            json.loads(p)
        except ValueError:
            print("payload is not JSON: %s" % p[:120], file=sys.stderr)
            return 1
    write_fixture(args.out, raw, payloads, sse_path)
    body = live_provenance(url, args.provider, args.scene, raw, received)
    body["endpoint_label"] = args.endpoint_label
    with open(prov_path, "w", encoding="utf-8") as fh:
        json.dump(body, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.write("\n")
    print("wrote %d/%d event payloads to %s (transport live-http-sse, %d bytes)"
          % (len(payloads), received, args.out, len(raw.encode("utf-8"))))
    print("provenance: %s" % prov_path)
    if args.cli:
        proc = run_adapter(args.cli, sse_path, args.provider)
        with open(adapter_path, "w", encoding="utf-8") as fh:
            fh.write(proc.stdout)
        print("adapter (rc=%d) wrote %s" % (proc.returncode, adapter_path))
        for line in proc.stdout.splitlines():
            print("  " + line)
        if proc.returncode != 0:
            print(proc.stderr[:400], file=sys.stderr)
            return 1
    return 0


def loopback_main(args) -> int:
    outdir = args.out.rstrip("/")
    os.makedirs(outdir, exist_ok=True)
    names = list(SCENARIOS) if args.scenario == "all" else [args.scenario]
    failures = 0
    for name in names:
        sse_body, meta = SCENARIOS[name](args.stamp)
        raw, evidence = record_loopback(sse_body)
        text = raw.decode("utf-8", "replace")
        payloads = payloads_of_sse(text)
        if not payloads:
            print("loopback %s: the server sent no data: payload." % name,
                  file=sys.stderr)
            failures += 1
            continue
        for p in payloads:
            try:
                json.loads(p)
            except ValueError:
                print("loopback %s: payload is not JSON: %s" % (name, p[:120]),
                      file=sys.stderr)
                failures += 1
                break
        out = os.path.join(outdir, "loopback_%s.jsonl" % name)
        base = out[: -len(".jsonl")]
        sse_path = write_fixture(out, text, payloads, base + ".sse")
        write_expectations(out, name, meta)
        print(
            "loopback %-13s %5d bytes over %s -> %s (%d payloads)"
            % (name, evidence["response_bytes"], evidence["url"], out,
               len(payloads))
        )
        for key in ("status", "request_path", "anthropic_version",
                    "response_content_type"):
            print("  %-22s %s" % (key, evidence[key]))
        if args.cli:
            proc = run_adapter(args.cli, sse_path, "anthropic")
            adapter_out = base + ".adapter.jsonl"
            with open(adapter_out, "w", encoding="utf-8") as fh:
                fh.write(proc.stdout)
            print("  adapter rc=%d -> %s" % (proc.returncode, adapter_out))
            if proc.returncode != 0:
                print(proc.stderr[:400], file=sys.stderr)
                failures += 1
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
