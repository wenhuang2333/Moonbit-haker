def _assemble(name: str, events: list, stamp: bool) -> str:
    """The bytes the loopback server sends: a comment, then the real events."""
    parts = [
        ": provenance transport=loopback-sse scenario=%s wire=anthropic/v1/messages"
        " generator=code/tests/record_stream.py --loopback\n\n"
        % name,
        sse("jsonmend.provenance", provenance_event(name, stamp)),
    ]
    for event_name, payload in events:
        parts.append(sse(event_name, payload))
    return "".join(parts)


class _LoopbackHandler(http.server.BaseHTTPRequestHandler):
    """Serves one pre-built SSE body, written in fragments over a real socket."""

    protocol_version = "HTTP/1.0"
    server_version = "jsonmend-loopback/1.0"

    def log_message(self, *args) -> None:  # keep the transcript quiet
        pass

    def do_POST(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
        if self.path != LOOPBACK_PATH:
            self.send_error(404, "the adapter must POST %s" % LOOPBACK_PATH)
            return
        length = int(self.headers.get("content-length") or 0)
        body = self.rfile.read(length)
        state = self.server.loopback_state  # type: ignore[attr-defined]
        state["path"] = self.path
        state["content_type"] = self.headers.get("content-type", "")
        state["anthropic_version"] = self.headers.get("anthropic-version", "")
        state["request"] = body.decode("utf-8", "replace")
        self.send_response(200)
        self.send_header("content-type", "text/event-stream; charset=utf-8")
        self.send_header("cache-control", "no-cache")
        self.send_header("connection", "close")
        self.end_headers()
        # Write the body in uneven fragments, so the bytes really do arrive as
        # several socket writes, and so a UTF-8 sequence is split on the wire.
        for chunk in _fragment(state["body"]):
            try:
                self.wfile.write(chunk)
                self.wfile.flush()
            except (BrokenPipeError, ConnectionResetError):
                return
            time.sleep(0.001)
        # `truncated` ends here: the socket closes with no terminator event.


def _fragment(body: bytes):
    """Deterministic uneven split points over the body bytes."""
    sizes = [1, 7, 3, 64, 17, 5, 128, 11, 2, 33]
    out, i, k = [], 0, 0
    while i < len(body):
        n = sizes[k % len(sizes)]
        out.append(body[i : i + n])
        i += n
        k += 1
    return out


class _LoopbackServer(http.server.ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, body: bytes, state: dict) -> None:
        super().__init__((LOOPBACK_HOST, 0), _LoopbackHandler)
        self.loopback_state = state
        self.loopback_state["body"] = body

    @property
    def port(self) -> int:
        return self.server_address[1]


def record_loopback(body, timeout: float = 60.0) -> tuple[bytes, dict]:
    """POST an Anthropic request to the loopback server and read the SSE back."""
    if isinstance(body, str):
        body = body.encode("utf-8")
    state: dict = {}
    server = _LoopbackServer(body, state)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    url = "http://%s:%d%s" % (LOOPBACK_HOST, server.port, LOOPBACK_PATH)
    request = {
        "model": "loopback-anthropic-compatible",
        "max_tokens": 512,
        "stream": True,
        "tools": [TOOL],
        "tool_choice": {"type": "tool", "name": TOOL["name"]},
        "messages": [{"role": "user", "content": PROMPT}],
    }
    try:
        raw, status, ctype = post(
            url,
            {
                "content-type": "application/json",
                "anthropic-version": "2023-06-01",
            },
            request,
        )
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
    evidence = {
        "url": url,
        "request": state.get("request", ""),
        "request_path": state.get("path", ""),
        "request_content_type": state.get("content_type", ""),
        "anthropic_version": state.get("anthropic_version", ""),
        "status": status,
        "response_content_type": ctype,
        "response_bytes": len(raw),
        "response_sha256": hashlib.sha256(raw).hexdigest(),
    }
    return raw, evidence


