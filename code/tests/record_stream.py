#!/usr/bin/env python3
"""Record a real provider stream into a replayable fixture (FR-23 / FR-30).

The repository ships event *shapes* transcribed from the provider documentation
(see `code/docs/LLM_EVENTS.md`) and synthetic fixtures generated by
`gen_llm_fixtures.py`. Neither is a recording of a live call. This script makes
a real recording possible when credentials and a network are available, so a
maintainer can replace the transcribed shapes with captured bytes:

    ANTHROPIC_API_KEY=... python3 code/tests/record_stream.py \
        --provider anthropic --out code/llm/fixtures/anthropic_recorded.jsonl

    OPENAI_API_KEY=...    python3 code/tests/record_stream.py \
        --provider openai --out code/llm/fixtures/openai_recorded.jsonl

One JSON event payload per line is written, which is exactly the format
`jsonmend llm --batch` and the fixture tests read. The raw SSE body is kept next
to it as `<out>.sse` so a reviewer can check that no event was dropped.

The tool-call request is used, so the recording exercises the adapter rather
than the text path; add `--text` to record a plain text answer instead.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.request

ANTHROPIC_URL = "https://api.anthropic.com/v1/messages"
OPENAI_URL = "https://api.openai.com/v1/chat/completions"

TOOL = {
    "name": "get_weather",
    "description": "Return the weather of a city.",
    "input_schema": {
        "type": "object",
        "properties": {"location": {"type": "string"}, "unit": {"type": "string"}},
        "required": ["location"],
    },
}
PROMPT = "What is the weather in Paris, in celsius?"


def post(url: str, headers: dict, body: dict):
    req = urllib.request.Request(
        url,
        data=json.dumps(body).encode(),
        headers=headers,
        method="POST",
    )
    return urllib.request.urlopen(req, timeout=120)


def record_anthropic(api_key: str, text: bool):
    body = {
        "model": "claude-sonnet-4-5",
        "max_tokens": 512,
        "stream": True,
        "messages": [{"role": "user", "content": PROMPT}],
    }
    if not text:
        body["tools"] = [TOOL]
        body["tool_choice"] = {"type": "tool", "name": TOOL["name"]}
    with post(
        ANTHROPIC_URL,
        {
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        },
        body,
    ) as resp:
        return resp.read().decode("utf-8", "replace")


def record_openai(api_key: str, text: bool):
    body = {
        "model": "gpt-4o-mini",
        "stream": True,
        "messages": [{"role": "user", "content": PROMPT}],
    }
    if not text:
        body["tools"] = [
            {
                "type": "function",
                "function": {
                    "name": TOOL["name"],
                    "description": TOOL["description"],
                    "parameters": TOOL["input_schema"],
                },
            }
        ]
        body["tool_choice"] = {"type": "function", "function": {"name": TOOL["name"]}}
    with post(
        OPENAI_URL,
        {"authorization": "Bearer " + api_key, "content-type": "application/json"},
        body,
    ) as resp:
        return resp.read().decode("utf-8", "replace")


def payloads_of_sse(raw: str):
    """The `data:` payloads of an SSE body, in order, `[DONE]` excluded."""
    out = []
    for line in raw.splitlines():
        line = line.strip()
        if not line.startswith("data:"):
            continue
        data = line[len("data:") :].strip()
        if data == "" or data == "[DONE]":
            continue
        out.append(data)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", choices=["anthropic", "openai"], required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--text", action="store_true")
    args = ap.parse_args()

    env = "ANTHROPIC_API_KEY" if args.provider == "anthropic" else "OPENAI_API_KEY"
    key = os.environ.get(env, "")
    if key == "":
        print("%s is not set; nothing was recorded." % env, file=sys.stderr)
        return 2

    raw = (
        record_anthropic(key, args.text)
        if args.provider == "anthropic"
        else record_openai(key, args.text)
    )
    payloads = payloads_of_sse(raw)
    if not payloads:
        print("the stream carried no data: payload; nothing was written.", file=sys.stderr)
        return 1
    for p in payloads:
        try:
            json.loads(p)
        except ValueError:
            print("payload is not JSON: %s" % p[:120], file=sys.stderr)
            return 1
    with open(args.out + ".sse", "w", encoding="utf-8") as fh:
        fh.write(raw)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(payloads) + "\n")
    print("wrote %d event payloads to %s" % (len(payloads), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
