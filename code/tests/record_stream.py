#!/usr/bin/env python3
"""Record a provider stream into a replayable fixture (FR-23 / FR-30 / FR-38).

The repository ships event *shapes* transcribed from the provider documentation
(see `code/docs/LLM_EVENTS.md`) and synthetic fixtures generated by
`gen_llm_fixtures.py`. Neither is a recording. This script makes real recordings
possible in three ways:

1. live, against a provider (needs a key and a network):

       ANTHROPIC_API_KEY=... python3 code/tests/record_stream.py \\
           --provider anthropic --out code/llm/fixtures/live_anthropic.jsonl

2. live, against any Anthropic-compatible endpoint. The endpoint and the token
   may also come from a Claude Code settings file, so a maintainer never has to
   paste a secret into a shell:

       python3 code/tests/record_stream.py --provider anthropic \\
           --from-claude-settings --out code/llm/fixtures/live_relay.jsonl

3. loopback, with no third-party key at all: a local HTTP server on 127.0.0.1
   emits a real SSE byte stream in Anthropic `/v1/messages` wire format and the
   script reads it back over a real socket with a plain HTTP client. That proves
   the adapter works over actual SSE framing rather than a Python list of dicts:

       python3 code/tests/record_stream.py --loopback --out code/llm/fixtures

Every fixture is written twice: `<out>.sse` holds the raw bytes (so a reviewer
can check that no event was dropped) and `<out>.jsonl` holds one JSON event
payload per line, which is what every consumer in this repository expects. Both
carry a provenance line naming the transport, so a loopback run can never be
mistaken for a vendor capture. The loopback fixtures are byte deterministic
(`--stamp` adds a timestamp); live captures obviously are not.

The tool-call request is used, so the recording exercises the adapter rather
than the text path; add `--text` to record a plain text answer instead.
"""

