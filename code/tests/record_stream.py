def post(url: str, headers: dict, body: dict, max_bytes: int = 0) -> tuple:
    """POST `body`, returning `(bytes, status, content type)`."""
    req = urllib.request.Request(
        url,
        data=json.dumps(body).encode(),
        headers=headers,
        method="POST",
    )
    try:
        resp = urllib.request.urlopen(req, timeout=120)
    except urllib.error.HTTPError as exc:
        detail = exc.read(800).decode("utf-8", "replace")
        raise SystemExit("provider refused the request (HTTP %d): %s"
                         % (exc.code, detail)) from None
    status = resp.status
    ctype = resp.headers.get("content-type", "") if resp.headers else ""
    if max_bytes > 0:
        # A real truncation: read part of the body and drop the connection, the
        # way a caller that gave up on a slow stream would.
        raw = resp.read(max_bytes)
        resp.close()
        return raw, status, ctype
    with resp:
        return resp.read(), status, ctype


def claude_settings_env(path: str) -> dict:
    """`env` of a Claude Code settings file, for the endpoint and the token."""
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    env = data.get("env")
    if not isinstance(env, dict):
        raise SystemExit("%s has no `env` object" % path)
    return env


def record_anthropic(url: str, api_key: str, text: bool, auth_header: str,
                     scene: str = "tool_call", model: str = "") -> str:
    spec = LIVE_SCENES.get(scene, LIVE_SCENES["tool_call"])
    body = {
        "model": model or os.environ.get("JSONMEND_ANTHROPIC_MODEL",
                                         "claude-sonnet-4-5"),
        "max_tokens": spec["max_tokens"],
        "stream": True,
        "messages": [{"role": "user", "content": spec["prompt"]}],
    }
    if not text:
        body["tools"] = spec["tools"]
        body["tool_choice"] = spec["tool_choice"]
    headers = {
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
    }
    if auth_header == "authorization":
        headers["authorization"] = "Bearer " + api_key
    else:
        headers["x-api-key"] = api_key
    return post(url, headers, body)[0].decode("utf-8", "replace")


